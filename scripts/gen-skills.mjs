// Emits packages/mcp/src/skills.generated.ts from packages/mcp/skills/.
//
// The skills are served by the Workers build too, which has no filesystem, so
// they are compiled in as strings rather than read at runtime. The markdown
// under skills/ stays the source: edit it there, then run
// `npm run generate:skills`. CI regenerates and fails on any diff, so the two
// cannot drift.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "packages", "mcp", "skills");
const outPath = join(repoRoot, "packages", "mcp", "src", "skills.generated.ts");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

const files = walk(sourceDir)
  .map((path) => [relative(sourceDir, path).split(sep).join("/"), path])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  // Line endings normalised, so a Windows checkout generates the same file.
  .map(
    ([key, path]) =>
      `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(path, "utf8").replace(/\r\n/g, "\n"))},`,
  );

const out = `// Generated by scripts/gen-skills.mjs from packages/mcp/skills/. Do not edit.

export const SKILL_FILES: Readonly<Record<string, string>> = {
${files.join("\n")}
};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`wrote ${relative(repoRoot, outPath)} (${files.length} files)`);
